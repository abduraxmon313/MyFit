// Reproducible import of forest/wild berries from the public-domain USDA SR Legacy archive.
// Download: https://fdc.nal.usda.gov/download-datasets/
// Run: node scripts/build_forest_berry_catalog.cjs
const fs = require('node:fs');
const crypto = require('node:crypto');
const source = 'data_sources/usda/sr-legacy/FoodData_Central_sr_legacy_food_json_2018-04.json';
const raw = fs.readFileSync(source);
const foods = new Map(JSON.parse(raw).SRLegacyFoods.map(f => [f.fdcId, f]));
const category = 'O‘rmon mevalari';
// fdcId, Uzbek, Russian, English. Only raw berries; species follows USDA scientificName.
const entries = [
  [167762, 'Qulupnay', 'Клубника', 'Strawberry'],
  [167755, 'Malina', 'Малина', 'Raspberry'],
  [168997, 'Yovvoyi malina', 'Малина лесная', 'Wild raspberry'],
  [173946, 'Maymunjon (ejevika)', 'Ежевика', 'Blackberry'],
  [168982, 'Yovvoyi maymunjon (ejevika)', 'Ежевика лесная', 'Wild blackberry'],
  [171711, 'Ko‘k meva — golubika (madaniy)', 'Голубика садовая', 'Blueberry'],
  [167640, 'Yovvoyi ko‘k meva (Alyaska)', 'Голубика дикая аляскинская', 'Wild Alaska blueberry'],
  [169808, 'Gekelberri (Alyaska)', 'Гекльберри аляскинская', 'Huckleberry (Alaska)'],
  [169915, 'Oxelo mevasi (Gavayi)', 'Охело (гавайская голубика)', 'Ohelo berry'],
  [171722, 'Klyukva (yirik mevali)', 'Клюква крупноплодная', 'Cranberry'],
  [169805, 'Brusnika', 'Брусника', 'Lingonberry'],
  [169804, 'Kalina (Viburnum edule)', 'Калина съедобная', 'Highbush cranberry (Viburnum edule)'],
  [173963, 'Qora smorodina (qoraqat)', 'Чёрная смородина', 'Black currant'],
  [173964, 'Qizil va oq smorodina', 'Красная и белая смородина', 'Red and white currant'],
  [173030, 'Krijovnik', 'Крыжовник', 'Gooseberry'],
  [171727, 'Buzina', 'Бузина', 'Elderberry'],
  [169802, 'Moroshka', 'Морошка', 'Cloudberry'],
  [168048, 'Losos mevasi (Rubus spectabilis)', 'Малина великолепная', 'Salmonberry'],
  [168999, 'Virginiya cheryomuxasi', 'Черёмуха виргинская', 'Chokecherry'],
  [168998, 'Na’matak (yovvoyi)', 'Шиповник дикий', 'Wild rose hips'],
];
const fields = {1008:'calories',1003:'protein',1004:'fat',1005:'carbohydrates',1051:'water',1079:'fiber',2000:'sugars',1258:'saturatedFat',1292:'monounsaturatedFat',1293:'polyunsaturatedFat',1093:'sodiumMg',1092:'potassiumMg',1089:'ironMg',1087:'calciumMg',1253:'cholesterolMg',1091:'phosphorusMg',1090:'magnesiumMg',1109:'vitaminEMg',1095:'zincMg',1114:'vitaminDMcg'};
const vitaminCId = 1162; // FoodNutrition has no vitamin C field; shown in labelDetails.
const quoted = value => JSON.stringify(value).replace(/\$/g, '\\$');
const subset = [];
let dart = "part of 'uzbek_food_catalog.dart';\n\n// GENERATED by scripts/build_forest_berry_catalog.cjs. Do not edit by hand.\n// USDA SR Legacy: raw berries, nutrients and gram portions retained.\nfinal List<UzbekDish> _forestBerryDishes = [\n";
for (const [id, uz, ru, en] of entries) {
  const f = foods.get(id);
  if (!f) throw new Error(`Missing source ${id}`);
  const values = {};
  let vitaminC = null;
  for (const n of f.foodNutrients) {
    if (!Number.isFinite(n.amount) || n.amount < 0) continue;
    if (n.nutrient.id === vitaminCId) vitaminC = n.amount;
    const key = fields[n.nutrient.id];
    if (key) values[key] = n.amount;
  }
  for (const key of ['calories','protein','fat','carbohydrates']) if (values[key] == null) throw new Error(`Missing ${key}: ${id}`);
  if (values.sodiumMg != null) values.salt = values.sodiumMg * 2.5 / 1000;
  const servings = (f.foodPortions ?? []).filter(p => p.gramWeight > 0 && (p.portionDescription || p.modifier)).map(p => ({description:p.portionDescription || `${p.amount ?? 1} ${p.modifier}`, amount:p.gramWeight, unit:'g'}));
  const url = `https://fdc.nal.usda.gov/food-details/${id}/nutrients`;
  const species = f.scientificName ? ` Tur: ${f.scientificName.trim().replace(/\.+$/, '')}.` : '';
  const vitaminCText = vitaminC == null ? '' : `\nC vitamini: ${vitaminC} mg / 100 g.`;
  const details = `${url}\n100 g yeyiladigan qism, xom.${species} USDA manbasida yo‘q moddalar ko‘rsatilmaydi; nav, yetilganlik va o‘sgan joyiga qarab farq qilishi mumkin.${vitaminCText}`;
  subset.push({fdcId:id, description:f.description, scientificName:f.scientificName ?? null, source:url, names:{uz,ru,en}, category, nutrients:values, vitaminCMg:vitaminC, servings});
  dart += `  UzbekDish(\n    nutrition: FoodNutrition(\n      fdcId: -${id},\n      name: ${quoted(f.description)},\n      dataSource: ${quoted(`USDA SR Legacy · FDC ${id}`)},\n      productType: 'FRUIT — XOM',\n      ingredients: ${quoted(`100% ${uz} (xom), yeyiladigan qismi.`)},\n      labelDetails: ${quoted(details)},\n`;
  for (const [key, value] of Object.entries(values)) dart += `      ${key}: ${value},\n`;
  if (values.water == null) dart += '      water: 0,\n      hasWaterData: false,\n';
  dart += `      knownNutrients: {${Object.keys(values).map(quoted).join(', ')}},\n`;
  dart += `      servings: [${servings.map(s => `FoodServing(description: ${quoted(s.description)}, amount: ${s.amount})`).join(', ')}],\n`;
  dart += `    ),\n    nameUz: ${quoted(uz)},\n    nameRu: ${quoted(ru)},\n    nameEn: ${quoted(en)},\n    region: ${quoted(category)},\n    meals: _allMeals,\n  ),\n`;
}
dart += '];\n';
fs.writeFileSync('lib/data/forest_berry_catalog.dart', dart);
fs.writeFileSync('data_sources/forest_berry_catalog.json', JSON.stringify({source:'https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_json_2018-04.zip', sha256:crypto.createHash('sha256').update(raw).digest('hex'), foods:subset}, null, 2) + '\n');
console.log(`Generated ${entries.length} forest berries with source nutrients and portions.`);
