// Reproducible import of dried fruits from the public-domain USDA SR Legacy archive.
// Download: https://fdc.nal.usda.gov/download-datasets/
// Run: node scripts/build_dried_fruit_catalog.cjs
const fs = require('node:fs');
const crypto = require('node:crypto');
const source = 'data_sources/usda/sr-legacy/FoodData_Central_sr_legacy_food_json_2018-04.json';
const raw = fs.readFileSync(source);
const foods = new Map(JSON.parse(raw).SRLegacyFoods.map(f => [f.fdcId, f]));
const category = 'Quruq mevalar';
// fdcId, Uzbek, Russian, English. Dried (uncooked) fruits; sweetened ones are named so.
const entries = [
  [173941, 'Kuraga (o‘rik qoqi)', 'Курага', 'Dried apricots'],
  [171702, 'Kuraga, past namlikli', 'Курага обезвоженная', 'Apricots, low-moisture'],
  [168164, 'Oltin mayiz (sabza)', 'Изюм золотистый', 'Golden raisins'],
  [168165, 'Qora mayiz, danaksiz', 'Изюм тёмный без косточек', 'Dark raisins, seedless'],
  [168166, 'Danakli mayiz', 'Изюм с косточками', 'Raisins, seeded'],
  [171724, 'Mayda qora mayiz (korinka)', 'Коринка', 'Zante currants'],
  [168162, 'Chernosliv (olxo‘ri qoqi)', 'Чернослив', 'Prunes'],
  [168160, 'Chernosliv, past namlikli', 'Чернослив обезвоженный', 'Prunes, low-moisture'],
  [168191, 'Finik (Medjool)', 'Финик Меджул', 'Medjool dates'],
  [171726, 'Finik (Deglet Noor)', 'Финик Деглет Нур', 'Deglet Noor dates'],
  [174665, 'Anjir qoqi', 'Инжир сушёный', 'Dried figs'],
  [171691, 'Olma qoqi', 'Яблоки сушёные', 'Dried apples'],
  [173931, 'Olma qoqi, past namlikli', 'Яблоки обезвоженные', 'Apples, low-moisture'],
  [169121, 'Nok qoqi', 'Груша сушёная', 'Dried pears'],
  [169934, 'Shaftoli qoqi', 'Персик сушёный', 'Dried peaches'],
  [169932, 'Shaftoli qoqi, past namlikli', 'Персик обезвоженный', 'Peaches, low-moisture'],
  [169942, 'Xurmo qoqi', 'Хурма сушёная', 'Dried persimmon'],
  [168152, 'Jiyda qoqi (unabi)', 'Унаби сушёный', 'Dried jujube'],
  [171708, 'Olcha qoqi, shakarli', 'Вишня сушёная, сладкая', 'Dried tart cherries, sweetened'],
  [171723, 'Klyukva qoqi, shakarli', 'Клюква сушёная, сладкая', 'Dried cranberries, sweetened'],
  [168158, 'Ko‘k meva qoqi, shakarli', 'Голубика сушёная, сладкая', 'Dried blueberries, sweetened'],
  [173032, 'Goji (quritilgan)', 'Годжи сушёные', 'Dried goji berries'],
  [169091, 'Mango qoqi, shakarli', 'Манго сушёное, сладкое', 'Dried mango, sweetened'],
  [173945, 'Banan qoqi', 'Банан сушёный', 'Dehydrated bananas'],
  [169087, 'Lichi qoqi', 'Личи сушёный', 'Dried lychee'],
  [169907, 'Longan qoqi', 'Лонган сушёный', 'Dried longan'],
  [167781, 'Sukat (qandlangan meva)', 'Цукаты', 'Candied fruit'],
];
const fields = {1008:'calories',1003:'protein',1004:'fat',1005:'carbohydrates',1051:'water',1079:'fiber',2000:'sugars',1258:'saturatedFat',1292:'monounsaturatedFat',1293:'polyunsaturatedFat',1093:'sodiumMg',1092:'potassiumMg',1089:'ironMg',1087:'calciumMg',1253:'cholesterolMg',1091:'phosphorusMg',1090:'magnesiumMg',1109:'vitaminEMg',1095:'zincMg',1114:'vitaminDMcg'};
const vitaminCId = 1162; // FoodNutrition has no vitamin C field; shown in labelDetails.
const quoted = value => JSON.stringify(value).replace(/\$/g, '\\$');
const subset = [];
let dart = "part of 'uzbek_food_catalog.dart';\n\n// GENERATED by scripts/build_dried_fruit_catalog.cjs. Do not edit by hand.\n// USDA SR Legacy: dried fruits, nutrients and gram portions retained.\nfinal List<UzbekDish> _driedFruitDishes = [\n";
for (const [id, uz, ru, en] of entries) {
  const f = foods.get(id);
  if (!f) throw new Error(`Missing source ${id}`);
  const values = {};
  let vitaminC = null;
  for (const n of f.foodNutrients) {
    if (!Number.isFinite(n.amount) || n.amount < 0) continue;
    if (n.nutrient.id === vitaminCId) vitaminC = n.amount;
    const key = fields[n.nutrient.id];
    if (key) values[key] = n.amount;
  }
  for (const key of ['calories','protein','fat','carbohydrates']) if (values[key] == null) throw new Error(`Missing ${key}: ${id}`);
  if (values.sodiumMg != null) values.salt = values.sodiumMg * 2.5 / 1000;
  const servings = (f.foodPortions ?? []).filter(p => p.gramWeight > 0 && (p.portionDescription || p.modifier)).map(p => ({description:p.portionDescription || `${p.amount ?? 1} ${p.modifier}`, amount:p.gramWeight, unit:'g'}));
  const url = `https://fdc.nal.usda.gov/food-details/${id}/nutrients`;
  const species = f.scientificName ? ` Tur: ${f.scientificName.trim().replace(/\.+$/, '')}.` : '';
  const vitaminCText = vitaminC == null ? '' : `\nC vitamini: ${vitaminC} mg / 100 g.`;
  const details = `${url}\n100 g yeyiladigan qism, quritilgan.${species} USDA manbasida yo‘q moddalar ko‘rsatilmaydi; nav, yetilganlik va o‘sgan joyiga qarab farq qilishi mumkin.${vitaminCText}`;
  subset.push({fdcId:id, description:f.description, scientificName:f.scientificName ?? null, source:url, names:{uz,ru,en}, category, nutrients:values, vitaminCMg:vitaminC, servings});
  dart += `  UzbekDish(\n    nutrition: FoodNutrition(\n      fdcId: -${id},\n      name: ${quoted(f.description)},\n      dataSource: ${quoted(`USDA SR Legacy · FDC ${id}`)},\n      productType: 'FRUIT — QURITILGAN',\n      ingredients: ${quoted(`100% ${uz} (quritilgan), yeyiladigan qismi.`)},\n      labelDetails: ${quoted(details)},\n`;
  for (const [key, value] of Object.entries(values)) dart += `      ${key}: ${value},\n`;
  if (values.water == null) dart += '      water: 0,\n      hasWaterData: false,\n';
  dart += `      knownNutrients: {${Object.keys(values).map(quoted).join(', ')}},\n`;
  dart += `      servings: [${servings.map(s => `FoodServing(description: ${quoted(s.description)}, amount: ${s.amount})`).join(', ')}],\n`;
  dart += `    ),\n    nameUz: ${quoted(uz)},\n    nameRu: ${quoted(ru)},\n    nameEn: ${quoted(en)},\n    region: ${quoted(category)},\n    meals: _allMeals,\n  ),\n`;
}
dart += '];\n';
fs.writeFileSync('lib/data/dried_fruit_catalog.dart', dart);
fs.writeFileSync('data_sources/dried_fruit_catalog.json', JSON.stringify({source:'https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_json_2018-04.zip', sha256:crypto.createHash('sha256').update(raw).digest('hex'), foods:subset}, null, 2) + '\n');
console.log(`Generated ${entries.length} dried fruits with source nutrients and portions.`);
